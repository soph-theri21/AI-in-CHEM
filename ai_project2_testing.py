class Tox21NN(nn.Module):

    def __init__(self, input_dim, hidden_dim1, hidden_dim2,
                 dropout_rate=0.3):

        super(Tox21NN, self).__init__()

        # Fully connected feed-forward network
        self.network = nn.Sequential(
            nn.Linear(input_dim, hidden_dim1),
            nn.ReLU(),
            nn.Dropout(p=dropout_rate),

            nn.Linear(hidden_dim1, hidden_dim2),
            nn.ReLU(),
            nn.Dropout(p=dropout_rate),

            nn.Linear(hidden_dim2, 1)
        )

    def forward(self, x):
        return self.network(x)

def train_model(model, train_loader, X_val_tensor,
                y_val_tensor, epochs, learning_rate):

    # Binary classification loss
    criterion = nn.BCEWithLogitsLoss()

    # Adam optimizer
    optimizer = optim.Adam(
        model.parameters(),
        lr=learning_rate
    )

    # Store losses and metrics for plotting
    train_losses = []
    val_losses = []
    train_aucs = []
    val_aucs = []

    # Track the best-performing model
    best_val_auc = -float("inf")
    best_model_state = None
    best_epoch = None

    for epoch in range(epochs):

        # Training phase
        model.train()
        epoch_loss = 0

        for batch_X, batch_y in train_loader:

            optimizer.zero_grad()

            predictions = model(batch_X)

            loss = criterion(predictions, batch_y)

            loss.backward()
            optimizer.step()

            epoch_loss += loss.item() * len(batch_X)

        avg_train_loss = epoch_loss / len(train_loader.dataset)
        train_losses.append(avg_train_loss)

        # Validation phase
        model.eval()

        with torch.no_grad():

            val_predictions = model(X_val_tensor)

            val_loss = criterion(
                val_predictions,
                y_val_tensor
            )

            # Convert logits to probabilities
            val_probabilities = torch.sigmoid(
                val_predictions
            ).numpy().flatten()

            val_auc = roc_auc_score(
                y_val_tensor.numpy().flatten(),
                val_probabilities
            )

            # Training ROC-AUC
            train_X = train_loader.dataset.tensors[0]
            train_y = train_loader.dataset.tensors[1]

            # Evaluate training data in smaller batches
            train_predictions = torch.cat([
                model(batch)
                for batch in train_X.split(32)
            ], dim=0)

            train_probabilities = torch.sigmoid(
                train_predictions
            ).numpy().flatten()

            train_auc = roc_auc_score(
                train_y.numpy().flatten(),
                train_probabilities
            )

        val_losses.append(val_loss.item())
        train_aucs.append(train_auc)
        val_aucs.append(val_auc)

        # Save model weights if validation AUC improves
        if val_auc > best_val_auc:
            best_val_auc = val_auc
            best_epoch = epoch + 1
            best_model_state = copy.deepcopy(model.state_dict())

        print(
            f"Epoch {epoch+1}/{epochs} | "
            f"Train Loss: {avg_train_loss:.4f} | "
            f"Val Loss: {val_loss.item():.4f} | "
            f"Val AUC: {val_auc:.4f}"
        )

    # Restore the model from the best epoch
    model.load_state_dict(best_model_state)

    print(f"Best epoch: {best_epoch}")
    print(f"Best validation AUC: {best_val_auc:.4f}")

    return train_losses, val_losses, train_aucs, val_aucs

