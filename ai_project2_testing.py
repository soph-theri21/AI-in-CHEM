# Check gradient magnitudes for a trained model

def check_gradients(model, train_loader, max_batches=20):

    model.eval()
    criterion = nn.BCEWithLogitsLoss()

    gradient_norms = {}
    batch_counts = {}

    # Examine up to 20 training batches
    for batch_idx, (X_batch, y_batch) in enumerate(train_loader):

        if batch_idx >= max_batches:
            break

        model.zero_grad(set_to_none=True)

        # Forward pass
        predictions = model(X_batch)

        # Calculate loss
        loss = criterion(predictions, y_batch)

        # Backpropagation
        loss.backward()

        # Calculate gradient norm for each weight layer
        for name, parameter in model.named_parameters():

            if parameter.grad is not None and parameter.ndim >= 2:

                grad_norm = parameter.grad.detach().norm(2).item()

                gradient_norms[name] = (
                    gradient_norms.get(name, 0) + grad_norm
                )

                batch_counts[name] = batch_counts.get(name, 0) + 1

    # Calculate average gradient norm per layer
    for name in gradient_norms:
        gradient_norms[name] /= batch_counts[name]

    model.zero_grad(set_to_none=True)

    for name, norm in gradient_norms.items():
        print(f"{name}: {norm:.6f}")

    return gradient_norms

