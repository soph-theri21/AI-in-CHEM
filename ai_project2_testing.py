def one_hot_smiles(smiles_list, char_to_index, max_length):

    n_channels = len(char_to_index) + 1

    encoded = torch.zeros(
        len(smiles_list),
        n_channels,
        max_length,
        dtype=torch.float32
    )

    for i, smiles in enumerate(smiles_list):
        for j, char in enumerate(smiles[:max_length]):

            char_index = char_to_index.get(char, 0)
            encoded[i, char_index, j] = 1.0

    return encoded


