# Training function with early stopping

def train_model(model, train_loader, X_val_tensor,
                y_val_tensor, epochs, learning_rate,
                patience=10, min_delta=0.0, verbose=True):

    # Move model to GPU
    model = model.to(device)

    criterion = nn.BCEWithLogitsLoss().to(device)

    optimizer = optim.Adam(
        model.parameters(),
        lr=learning_rate
    )

    # Store training history
    train_losses = []
    val_losses = []
    train_aucs = []
    val_aucs = []

    # Track best model
    best_val_auc = -float("inf")
    best_model_state = None
    best_epoch = None

    # Early stopping counter
    epochs_without_improvement = 0

    for epoch in range(epochs):

        # Training phase
        model.train()
        epoch_loss = 0

        for batch_X, batch_y in train_loader:

            # Move training batch to GPU
            batch_X = batch_X.to(device)
            batch_y = batch_y.to(device)

            optimizer.zero_grad()

            predictions = model(batch_X)

            loss = criterion(predictions, batch_y)

            loss.backward()
            optimizer.step()

            epoch_loss += loss.item() * len(batch_X)

        avg_train_loss = epoch_loss / len(train_loader.dataset)
        train_losses.append(avg_train_loss)

        # Validation phase
        model.eval()

        with torch.no_grad():

            # Validation predictions using GPU
            val_predictions = torch.cat([
                model(batch.to(device))
                for batch in X_val_tensor.split(32)
            ], dim=0)

            val_loss = criterion(
                val_predictions,
                y_val_tensor.to(device)
            )

            val_probabilities = torch.sigmoid(
                val_predictions
            ).cpu().numpy().flatten()

            val_auc = roc_auc_score(
                y_val_tensor.numpy().flatten(),
                val_probabilities
            )

            # Training ROC-AUC
            train_X = train_loader.dataset.tensors[0]
            train_y = train_loader.dataset.tensors[1]

            train_predictions = torch.cat([
                model(batch.to(device))
                for batch in train_X.split(32)
            ], dim=0)

            train_probabilities = torch.sigmoid(
                train_predictions
            ).cpu().numpy().flatten()


            train_auc = roc_auc_score(
                train_y.numpy().flatten(),
                train_probabilities
            )

        val_losses.append(val_loss.item())
        train_aucs.append(train_auc)
        val_aucs.append(val_auc)

        # Check for validation improvement
        if val_auc > best_val_auc + min_delta:

            best_val_auc = val_auc
            best_epoch = epoch + 1

            best_model_state = copy.deepcopy(
                model.state_dict()
            )

            # Reset patience counter
            epochs_without_improvement = 0

        else:
            epochs_without_improvement += 1

        if verbose:
            print(
                f"Epoch {epoch+1}/{epochs} | "
                f"Train Loss: {avg_train_loss:.4f} | "
                f"Val Loss: {val_loss.item():.4f} | "
                f"Val AUC: {val_auc:.4f}"
            )

        # Early stopping condition
        if epochs_without_improvement >= patience:

            if verbose:
                print(
                    f"\nEarly stopping at epoch {epoch+1}"
                )

            break

    # Restore best model weights
    model.load_state_dict(best_model_state)

    if verbose:
        print(f"\nBest epoch: {best_epoch}")
        print(f"Best validation AUC: {best_val_auc:.4f}")
        print(f"Total epochs trained: {len(train_losses)}")

    return train_losses, val_losses, train_aucs, val_aucs

