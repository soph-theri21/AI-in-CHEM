def create_saved_study(study_name):
    """Resume a previously saved Optuna study, if one exists."""
    local_db = LOCAL_OPTUNA_DIR / f'{study_name}.db'
    drive_db = RESULTS_DIR / f'{study_name}.db'

    if drive_db.exists():
        # Copy from Drive to local storage to avoid SQLite locking on Drive.
        import shutil
        shutil.copy2(drive_db, local_db)
        print(f'Resuming saved study: {study_name} from Google Drive')

    study = optuna.create_study(
        study_name=study_name,
        storage=f'sqlite:///{local_db}',
        direction='maximize',
        sampler=optuna.samplers.TPESampler(seed=21),
        load_if_exists=True
    )
    return study, local_db, drive_db


def save_study_backup(study, trial, local_db, drive_db):
    """Copy a consistent database snapshot to Drive after each trial."""
    temp_db = drive_db.with_suffix('.tmp.db')
    with sqlite3.connect(str(local_db)) as source:
        with sqlite3.connect(str(temp_db)) as destination:
            source.backup(destination)
    temp_db.replace(drive_db)


