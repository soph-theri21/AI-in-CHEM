def generate_cnn_channels(n_layers, initial_channels, channel_growth):

    channels = []

    for i in range(n_layers):

        if channel_growth == "constant":
            n_channels = initial_channels

        elif channel_growth == "double":
            n_channels = initial_channels * (2 ** i)

        elif channel_growth == "add_32":
            n_channels = initial_channels + 32 * i

        else:
            raise ValueError("Unknown channel growth strategy")

        channels.append(n_channels)

    return channels


# CNN architecture with adjustable hyperparameters
class TunableSmilesCNN(nn.Module):

    def __init__(self, input_channels, channels,
                 kernel_size, hidden_size,
                 conv_dropout, dense_dropout):

        super().__init__()

        layers = []
        in_channels = input_channels

        # Build convolutional layers
        for out_channels in channels:

            layers.extend([
                nn.Conv1d(
                    in_channels,
                    out_channels,
                    kernel_size=kernel_size,
                    padding=kernel_size // 2
                ),
                nn.BatchNorm1d(out_channels),
                nn.ReLU(),
                nn.MaxPool1d(2),
                nn.Dropout1d(conv_dropout)
            ])

            in_channels = out_channels

        # Reduce sequence dimension
        layers.append(nn.AdaptiveMaxPool1d(1))

        self.features = nn.Sequential(*layers)

        # Fully connected classifier
        self.classifier = nn.Sequential(
            nn.Flatten(),
            nn.Linear(in_channels, hidden_size),
            nn.ReLU(),
            nn.Dropout(dense_dropout),
            nn.Linear(hidden_size, 1)
        )

    def forward(self, x):

        x = self.features(x)
        x = self.classifier(x)

        return x

