# Model 2: CNN with Multi-Head Self-Attention

class SmilesAttentionCNN(nn.Module):

    def __init__(self, input_channels, num_heads=4):
        super().__init__()

        # Same convolutional layers as baseline CNN
        self.features = nn.Sequential(
            nn.Conv1d(input_channels, 16,
                      kernel_size=5, padding=2),
            nn.BatchNorm1d(16),
            nn.ReLU(),
            nn.MaxPool1d(2),
            nn.Dropout1d(0.1),

            nn.Conv1d(16, 32,
                      kernel_size=5, padding=2),
            nn.BatchNorm1d(32),
            nn.ReLU(),
            nn.MaxPool1d(2),
            nn.Dropout1d(0.1)
        )

        # Multi-head self-attention
        self.attention = nn.MultiheadAttention(
            embed_dim=32,
            num_heads=num_heads,
            dropout=0.1,
            batch_first=True
        )

        # Normalize attention output
        self.layer_norm = nn.LayerNorm(32)

        # Same classification head as baseline CNN
        self.classifier = nn.Sequential(
            nn.Linear(32, 32),
            nn.ReLU(),
            nn.Dropout(0.5),
            nn.Linear(32, 1)
        )

    def forward(self, x):

        # Identify real SMILES positions before convolutions
        valid_mask = (x.abs().sum(dim=1) > 0)

        # Account for the two MaxPool1d layers
        mask = valid_mask.float().unsqueeze(1)

        mask = F.max_pool1d(mask, kernel_size=2)
        mask = F.max_pool1d(mask, kernel_size=2)

        valid_mask = mask.squeeze(1).bool()

        # CNN feature extraction
        x = self.features(x)

        # Convert from [batch, channels, length]
        # to [batch, length, channels]
        x = x.transpose(1, 2)

        # Apply multi-head self-attention
        attention_output, _ = self.attention(
            x, x, x,
            key_padding_mask=~valid_mask,
            need_weights=False
        )

        # Residual connection and normalization
        x = self.layer_norm(x + attention_output)

        # Exclude padded positions from global max pooling
        x = x.masked_fill(
            ~valid_mask.unsqueeze(-1),
            torch.finfo(x.dtype).min
        )

        # Global max pooling over sequence positions
        x = x.max(dim=1).values

        # Classification
        x = self.classifier(x)

        return x

