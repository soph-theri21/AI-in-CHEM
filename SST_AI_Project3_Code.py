# Convert SMILES to one-hot encoded tensors

def one_hot_smiles(smiles_list, char_to_index, max_length):

    n_channels = len(char_to_index) + 2

    encoded = torch.zeros(
        len(smiles_list),
        n_channels,
        max_length,
        dtype=torch.float32
    )

    # Mask indicates which positions contain SMILES characters
    attention_mask = torch.zeros(
        len(smiles_list),
        max_length,
        dtype=torch.bool
    )

    for i, smiles in enumerate(smiles_list):
        for j, char in enumerate(smiles[:max_length]):

            char_index = char_to_index.get(char, UNK_IDX)

            encoded[i, char_index, j] = 1.0
            attention_mask[i, j] = True

    return encoded, attention_mask


