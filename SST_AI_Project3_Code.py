class TunableSmilesAttentionCNN(nn.Module):
    def __init__(self, input_channels, channels, kernel_size,
                 hidden_size, conv_dropout, dense_dropout,
                 num_heads, attention_dropout):
        super().__init__()

        layers = []
        in_channels = input_channels
        for out_channels in channels:
            layers.extend([
                nn.Conv1d(in_channels, out_channels,
                          kernel_size=kernel_size, padding=kernel_size // 2),
                nn.BatchNorm1d(out_channels),
                nn.ReLU(),
                nn.MaxPool1d(2),
                nn.Dropout1d(conv_dropout)
            ])
            in_channels = out_channels

        self.features = nn.Sequential(*layers)
        self.n_pool_layers = len(channels)
        self.attention = nn.MultiheadAttention(
            embed_dim=in_channels,
            num_heads=num_heads,
            dropout=attention_dropout,
            batch_first=True
        )
        self.layer_norm = nn.LayerNorm(in_channels)
        self.classifier = nn.Sequential(
            nn.Linear(in_channels, hidden_size),
            nn.ReLU(),
            nn.Dropout(dense_dropout),
            nn.Linear(hidden_size, 1)
        )

    def forward(self, x):
        valid_mask = (x.abs().sum(dim=1) > 0)
        mask = valid_mask.float().unsqueeze(1)
        for _ in range(self.n_pool_layers):
            mask = F.max_pool1d(mask, kernel_size=2)
        valid_mask = mask.squeeze(1).bool()

        x = self.features(x)
        x = x.transpose(1, 2)
        attention_output, _ = self.attention(
            x, x, x, key_padding_mask=~valid_mask, need_weights=False
        )
        x = self.layer_norm(x + attention_output)
        x = x.masked_fill(
            ~valid_mask.unsqueeze(-1), torch.finfo(x.dtype).min
        )
        x = x.max(dim=1).values
        return self.classifier(x)

